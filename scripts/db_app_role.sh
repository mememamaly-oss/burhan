#!/usr/bin/env bash
# DB PRIVILEGE SEPARATION (owner order 2026-10-31, items 1.2 + 2.3).
#
# RED (proven live, this repo, 2026-10-31): with the app connecting as the
# DB owner (postgres / the compose superuser), the application's own Prisma
# connection could execute
#     TRUNCATE TABLE "AuditLog"            -> trail erased, trigger CANNOT fire
#     ALTER TABLE "AuditLog" DISABLE TRIGGER + UPDATE  -> trail rewritten
#     DROP TABLE <anything>                -> schema destroyed
# The 20261031095442 immutability trigger only covers UPDATE/DELETE —
# TRUNCATE never fires row-level triggers, so the ONLY structural defense
# is that the app account simply LACKS the privilege.
#
# This script (idempotent; run as the OWNER after every migrate deploy)
# provisions `burhan_app`: LOGIN, DML-only. No TRUNCATE, no DDL, no
# role/database creation. The migration/owner connection stays separate.
#
# Env:
#   BURHAN_APP_DB_USER      (default burhan_app)
#   BURHAN_APP_DB_PASSWORD  (default: the documented local-dev value — the
#                            pgserver cluster is loopback-only; CI and prod
#                            MUST set their own)
#   MIGRATION_DATABASE_URL  owner connection (default: DATABASE_URL, else
#                            the local pgserver cluster)
#
# Stdout: the APP connection URL (same host/port/db, user burhan_app).
set -euo pipefail
cd "$(dirname "$0")/.."

APP_USER="${BURHAN_APP_DB_USER:-burhan_app}"
APP_PW="${BURHAN_APP_DB_PASSWORD:-local-dev-app-role-password}"
[ "$APP_PW" = "local-dev-app-role-password" ] && \
  echo "WARN: using the default local-dev app-role password (loopback dev only)" >&2

OWNER_URL="${MIGRATION_DATABASE_URL:-${DATABASE_URL:-}}"
case "$OWNER_URL" in
  postgresql://*|postgres://*) : ;;
  *) OWNER_URL="$(bash scripts/pg_dev_start.sh)" ;;
esac

# host/port/db from the owner URL. The netloc is taken WITHOUT any
# userinfo (user[:pass]@ must be stripped — with the owner credentials
# left in, the emitted app URL double-stacks userinfo and libpq then
# authenticates burhan_app with a corrupted password; observed in CI:
# "credentials for `burhan_app` are not valid" while trust-auth local
# clusters silently passed).
NETLOC="$(echo "$OWNER_URL" | sed -E 's#^postgres(ql)?://([^/?]+).*#\2#')"
HOSTPORT="${NETLOC##*@}"
DBNAME="$(echo "$OWNER_URL" | sed -E 's#^.*/([^/?]+)([?].*)?$#\1#')"
case "$DBNAME" in *[!A-Za-z0-9_]*|'') echo "FATAL: unusable database name from URL: '$DBNAME'" >&2; exit 1;; esac
case "$APP_USER" in *[!a-z0-9_]*|'') echo "FATAL: app role name must be [a-z0-9_]: '$APP_USER'" >&2; exit 1;; esac

SQL="$(mktemp /tmp/db_app_role.XXXXXX.sql)"
trap 'rm -f "$SQL"' EXIT
chmod 600 "$SQL"
cat >"$SQL" <<EOF
-- generated by scripts/db_app_role.sh — DO NOT hand-edit
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '$APP_USER') THEN
    CREATE ROLE $APP_USER LOGIN PASSWORD '$APP_PW'
      NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
  ELSE
    ALTER ROLE $APP_USER LOGIN PASSWORD '$APP_PW'
      NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
  END IF;
END
\$\$;
GRANT CONNECT ON DATABASE "$DBNAME" TO $APP_USER;
GRANT USAGE ON SCHEMA public TO $APP_USER;
-- DML only: no TRUNCATE (not grantable separately from DELETE in one verb —
-- it is simply never granted), no REFERENCES, no TRIGGER, no DDL.
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO $APP_USER;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO $APP_USER;
-- future tables from later migrations (re-run this script after each
-- migrate deploy; the integration runner does exactly that)
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO $APP_USER;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO $APP_USER;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
EOF

# psql when available (local pgserver bin is not on PATH — resolve it),
# else prisma db execute (CI/local both have bunx)
PSQL_BIN="$(command -v psql || true)"
if [ -z "$PSQL_BIN" ]; then
  PGBIN="$(python3 -c 'import pgserver,os,sys; sys.stdout.write(os.path.dirname(pgserver.__file__)+"/pginstall/bin")' 2>/dev/null || true)"
  [ -x "$PGBIN/psql" ] && PSQL_BIN="$PGBIN/psql"
fi
if [ -n "$PSQL_BIN" ]; then
  PGPASSWORD_AVOID='' # owner URLs here are trust/passwordless loopback or embed creds
  # R17-4: options BEFORE the connection string. The old order (URL
  # first, then -v/-f) made MinGW psql on Windows silently IGNORE the
  # options: the SQL file never executed, psql still exited 0, and this
  # script announced success while the role did not exist (proven live:
  # pg_roles had no burhan_app after a "successful" run).
  "$PSQL_BIN" -v ON_ERROR_STOP=1 -f "$SQL" "$OWNER_URL" >/dev/null
else
  bunx prisma db execute --file "$SQL" --url "$OWNER_URL"
fi

# R17-4: VERIFY, don't assume — query pg_roles for the role instead of
# trusting the provisioning command's exit code (the same discipline as
# the TRUNCATE-trigger discovery). Covers BOTH silent-failure shapes:
# an option-order quirk that skips the SQL entirely, or any execution
# path that reports success without doing the work. The psql branch
# verifies through -c (a DIFFERENT mechanism than the -f it just used —
# a psql that mishandles file execution cannot also hide the catalog
# check); the prisma branch uses a raising DO block (prisma db execute
# does not return query output).
if [ -n "$PSQL_BIN" ]; then
  FOUND="$("$PSQL_BIN" -v ON_ERROR_STOP=1 -tA \
    -c "SELECT 1 FROM pg_roles WHERE rolname = '${APP_USER}'" \
    "$OWNER_URL" 2>/dev/null || true)"
  if [ "$FOUND" != "1" ]; then
    echo "FATAL: verification query failed — role $APP_USER not confirmed in pg_roles" >&2
    exit 1
  fi
else
  VSQL="$(mktemp /tmp/db_app_role_verify.XXXXXX.sql)"
  trap 'rm -f "$SQL" "$VSQL"' EXIT
  chmod 600 "$VSQL"
  cat >"$VSQL" <<EOF
-- generated by scripts/db_app_role.sh — role verification (DO NOT hand-edit)
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '$APP_USER') THEN
    RAISE EXCEPTION 'role $APP_USER absent from pg_roles — the provisioning SQL did not actually execute';
  END IF;
END \$\$;
EOF
  if ! bunx prisma db execute --file "$VSQL" --url "$OWNER_URL"; then
    echo "FATAL: verification query failed — role $APP_USER not confirmed in pg_roles" >&2
    exit 1
  fi
fi

echo "postgresql://$APP_USER:$(python3 -c 'import urllib.parse,sys; sys.stdout.write(urllib.parse.quote(sys.argv[1]))' "$APP_PW")@${HOSTPORT}/${DBNAME}"
